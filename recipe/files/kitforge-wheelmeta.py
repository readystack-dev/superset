#!/usr/bin/env python3
"""kitforge-wheelmeta.py — widen a published wheel's declared dependency ranges (strategy source.wheel_requires_overrides).

GENERATED by gen_dockerfile.py (L-009 Python kit). pip has no override mechanism: a dependency range an application
declares in its wheel metadata (Requires-Dist) wins over every constraint, so a CVE fix that lies outside it cannot be
installed. This helper rewrites ONLY the version specifiers of the named Requires-Dist lines in the wheel's METADATA
(extras and environment markers kept), adds the build tag to its WHEEL file, updates those two entries in RECORD, and
writes the result under a wheel build tag, which pip prefers over the same version without one. No file of the
application itself changes: every other member is copied byte for byte with its original zip header, so the result is
the same bytes on every run. The original is checked against its pinned sha256 first; RECORD_DIR gets a JSON record of
each change (original and result sha256, every Requires-Dist before and after), shipped in vendored/wheel-overrides/.
To check an archive: download the original from PyPI, run `apply` on it with the kit's kitforge-wheel-overrides.json,
and compare the result's sha256 with the record and with the file in vendored/wheelhouse/.

    kitforge-wheelmeta.py apply SPEC.json IN_DIR OUT_DIR RECORD_DIR

Fails closed: a sha256 mismatch, an override naming a requirement the METADATA does not declare, or a specifier that
is not a plain comparison list stops the build. stdlib only.
"""
import base64
import hashlib
import json
import os
import re
import sys
import urllib.parse
import zipfile

REQ_RE = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)\s*(?P<extras>\[[^\]]*\])?\s*(?P<spec>[^;]*?)\s*(?P<marker>;.*)?$")
OP = r"(===|==|!=|~=|<=|>=|<|>)"
SPEC_RE = re.compile(rf"^\s*{OP}\s*[0-9][A-Za-z0-9.*+!_-]*\s*(,\s*{OP}\s*[0-9][A-Za-z0-9.*+!_-]*\s*)*$")


def canon(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def record_hash(data):
    return "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()


def rewrite_metadata(text, requires):
    """(new METADATA text, [{requirement, from, to, line}]): only the specifier of each named Requires-Dist changes."""
    want = {canon(k): v.replace(" ", "") for k, v in requires.items()}
    seen, changes, out = set(), [], []
    for line in text.split("\n"):
        if line.startswith("Requires-Dist:"):
            body = line[len("Requires-Dist:"):].strip()
            m = REQ_RE.match(body)
            if m and canon(m.group("name")) in want:
                key = canon(m.group("name"))
                new = m.group("name") + (m.group("extras") or "") + want[key]
                if m.group("marker"):
                    new += "; " + m.group("marker")[1:].strip()
                changes.append({"requirement": body, "from": (m.group("spec") or "").replace(" ", ""),
                                "to": want[key], "line": new})
                seen.add(key)
                line = "Requires-Dist: " + new
        out.append(line)
    missing = sorted(set(want) - seen)
    if missing:
        sys.exit(f"kitforge-wheelmeta: the wheel declares no Requires-Dist for {missing}: an override must widen a "
                 "range the wheel really declares (check the name)")
    return "\n".join(out), changes


def apply_one(ent, in_dir, out_dir, rec_dir):
    for k in ("dist", "version", "wheel", "sha256", "build_tag", "requires"):
        if not ent.get(k):
            sys.exit(f"kitforge-wheelmeta: override entry is missing {k!r}: {ent}")
    for name, spec in ent["requires"].items():
        if not SPEC_RE.match(spec):
            sys.exit(f"kitforge-wheelmeta: {name}: {spec!r} is not a plain version range (e.g. '>=50.0.2,<51')")
    if not re.fullmatch(r"\d[A-Za-z0-9_.]*", ent["build_tag"]):
        sys.exit(f"kitforge-wheelmeta: build_tag {ent['build_tag']!r} must start with a digit (the wheel spec)")
    src = os.path.join(in_dir, ent["wheel"])
    if not os.path.isfile(src):
        sys.exit(f"kitforge-wheelmeta: {src} was not downloaded (pip chose another file for "
                 f"{ent['dist']}=={ent['version']}: pin the file pip installs)")
    got = sha256_file(src)
    if got != ent["sha256"].lower():
        sys.exit(f"kitforge-wheelmeta: {ent['wheel']}: sha256 {got} is not the pinned {ent['sha256']}")
    parts = ent["wheel"][:-4].split("-")
    if len(parts) != 5 or canon(parts[0]) != canon(ent["dist"]) or parts[1] != ent["version"]:
        sys.exit(f"kitforge-wheelmeta: {ent['wheel']} is not a build-tag-free wheel of {ent['dist']} {ent['version']}")
    out_name = "-".join([parts[0], parts[1], ent["build_tag"]] + parts[2:]) + ".whl"
    distinfo = f"{parts[0]}-{parts[1]}.dist-info/"
    with zipfile.ZipFile(src) as zin:
        infos = zin.infolist()
        names = [i.filename for i in infos]
        for need in ("METADATA", "WHEEL", "RECORD"):
            if distinfo + need not in names:
                sys.exit(f"kitforge-wheelmeta: {ent['wheel']} has no {distinfo}{need}")
        meta, changes = rewrite_metadata(zin.read(distinfo + "METADATA").decode("utf-8"), ent["requires"])
        wheel_lines = [ln for ln in zin.read(distinfo + "WHEEL").decode("utf-8").split("\n") if not ln.startswith("Build:")]
        while wheel_lines and wheel_lines[-1] == "":
            wheel_lines.pop()
        new = {distinfo + "METADATA": meta.encode("utf-8"),
               distinfo + "WHEEL": ("\n".join(wheel_lines + [f"Build: {ent['build_tag']}"]) + "\n").encode("utf-8")}
        rec = []
        for row in zin.read(distinfo + "RECORD").decode("utf-8").splitlines():
            path = row.split(",", 1)[0]
            if path in new:
                row = f"{path},{record_hash(new[path])},{len(new[path])}"
            rec.append(row)
        new[distinfo + "RECORD"] = ("\n".join(rec) + "\n").encode("utf-8")
        os.makedirs(out_dir, exist_ok=True)
        dst = os.path.join(out_dir, out_name)
        with zipfile.ZipFile(dst + ".tmp", "w") as zout:
            for info in infos:
                data = new.get(info.filename)
                if data is None:
                    zout.writestr(info, zin.read(info.filename), compress_type=info.compress_type)
                else:
                    zi = zipfile.ZipInfo(info.filename, date_time=info.date_time)
                    zi.compress_type, zi.external_attr, zi.create_system = (info.compress_type, info.external_attr,
                                                                            info.create_system)
                    zout.writestr(zi, data)
        os.replace(dst + ".tmp", dst)
    record = {"dist": ent["dist"], "version": ent["version"], "original_wheel": ent["wheel"], "original_sha256": got,
              "wheel": out_name, "sha256": sha256_file(dst), "build_tag": ent["build_tag"],
              "changed_files": sorted(new), "requires_changes": changes}
    os.makedirs(rec_dir, exist_ok=True)
    with open(os.path.join(rec_dir, f"{canon(ent['dist'])}-{ent['version']}.json"), "w") as f:
        json.dump(record, f, indent=2, sort_keys=True)
        f.write("\n")
    for c in changes:
        print(f"kitforge-wheelmeta: {ent['dist']} {ent['version']}: Requires-Dist {c['requirement']!r} -> {c['line']!r}")
    print(f"kitforge-wheelmeta: wrote {out_name} (sha256 {record['sha256']})")
    return record


def main(argv):
    if len(argv) != 6 or argv[1] != "apply":
        sys.exit(__doc__)
    spec = json.load(open(argv[2]))
    if not isinstance(spec, list) or not spec:
        sys.exit("kitforge-wheelmeta: SPEC.json must be a non-empty list")
    for ent in spec:
        apply_one(ent, argv[3], argv[4], argv[5])


if __name__ == "__main__":
    main(sys.argv)
